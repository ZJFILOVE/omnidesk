"""Path containment, bounded reads, and atomic protected subtitle writes for plugin-fnos-nas."""

from __future__ import annotations

import errno
import hashlib
import json
import os
import re
import stat
import threading
import time
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

MAX_SUBTITLE_BYTES = 8 * 1024 * 1024
MAX_METADATA_BYTES = 512 * 1024
MAX_SYNC_BYTES = 4 * 1024 * 1024
SUBTITLE_EXTENSIONS: frozenset[str] = frozenset({".srt", ".vtt", ".ass", ".ssa"})
_OMNIDESK_MARKERS: tuple[str, ...] = ("OMNIDESK-MANAGED", "omnidesk:managed", "Generated by OmniDesk")
_MANUAL_MARKERS: tuple[str, ...] = ("人工精校", "人工校对", "手工校对", "手校", "human-curated", "manual-curated")
_WRITE_LOCK = threading.RLock()


class MountValidationError(Exception):
    """Domain validation error carrying an OmniDesk machine error_code."""

    def __init__(self, message: str, error_code: str, *, details: Mapping[str, Any] | None = None) -> None:
        super().__init__(message)
        self.error_code = error_code
        self.details = dict(details) if details else {}


def redact_secrets(text: str, extra_secrets: Iterable[str] = ()) -> str:
    """Scrub secret values and common credential patterns from error text."""
    if not text:
        return ""
    scrubbed = text
    for secret in sorted({s for s in extra_secrets if isinstance(s, str) and len(s) >= 4}, key=len, reverse=True):
        scrubbed = scrubbed.replace(secret, "[REDACTED]")
    scrubbed = re.sub(r"(?i)(Bearer\s+)[A-Za-z0-9._~+/=-]{6,}", r"\1[REDACTED]", scrubbed)
    scrubbed = re.sub(
        r"(?i)\b(api[_-]?key|secret|token|password|cookie|authorization)\s*([=:])\s*([^\s,;'\"]+)",
        r"\1\2[REDACTED]",
        scrubbed,
    )
    return scrubbed


def _has_traversal_parts(raw_path: str) -> bool:
    if "\x00" in raw_path:
        return True
    tokens = [tok for tok in re.split(r"[/\\]+", raw_path) if tok]
    return ".." in tokens or ".." in Path(raw_path).parts


def validate_mount_root(raw_path: str | None) -> Path:
    """Validate user-configured mount_root: configured, no traversal, exists, dir, readable."""
    if not isinstance(raw_path, str) or not raw_path.strip():
        raise MountValidationError("尚未配置 NAS 挂载根目录 (mount_root)", "not_configured")
    raw = raw_path.strip()
    if "\x00" in raw or _has_traversal_parts(raw):
        raise MountValidationError("挂载路径包含非法穿越字符 (.. 或 NUL)", "path_safety")
    candidate = Path(raw).expanduser()
    if not candidate.is_absolute():
        raise MountValidationError("NAS 挂载根目录必须为绝对路径", "invalid_argument")
    if not candidate.exists():
        raise MountValidationError(f"NAS 挂载路径不存在: {candidate}", "not_found")
    if not candidate.is_dir():
        raise MountValidationError(f"NAS 挂载路径不是目录: {candidate}", "invalid_argument")
    resolved = candidate.resolve()
    if not os.access(resolved, os.R_OK | os.X_OK):
        raise MountValidationError(f"NAS 挂载目录不可读: {resolved}", "permission_denied")
    try:
        with os.scandir(resolved) as entries:
            next(entries, None)
    except PermissionError as exc:
        raise MountValidationError(f"NAS 挂载目录权限不足: {resolved}", "permission_denied") from exc
    except OSError as exc:
        raise MountValidationError(f"NAS 挂载目录读取失败: {exc}", "service_offline") from exc
    return resolved


def _extract_relative_parts(mount_root: Path, target_path: str) -> list[str]:
    if not isinstance(target_path, str) or not target_path.strip():
        raise MountValidationError("目标路径不能为空", "invalid_argument")
    raw = target_path.strip()
    if "\x00" in raw or _has_traversal_parts(raw):
        raise MountValidationError("目标路径包含非法穿越字符 (.. 或 NUL)", "path_safety")
    candidate = Path(raw)
    if candidate.is_absolute():
        resolved_root = mount_root.resolve()
        for base in (mount_root, resolved_root):
            try:
                rel = candidate.relative_to(base)
                return [p for p in rel.parts if p and p != "."]
            except ValueError:
                continue
        raise MountValidationError("绝对路径超出 NAS 挂载根目录范围", "path_safety")
    parts = [p for p in re.split(r"[/\\]+", raw) if p and p != "."]
    if not parts or any(p == ".." or ":" in p for p in parts):
        raise MountValidationError("目标路径不合法或包含穿越组件", "path_safety")
    return parts


def resolve_contained_path(
    mount_root: Path,
    target_path: str,
    *,
    allow_symlinks: bool = False,
    reject_hidden: bool = True,
) -> Path:
    """Resolve a path strictly inside mount_root and reject traversal or symlink escapes."""
    resolved_root = mount_root.resolve()
    parts = _extract_relative_parts(mount_root, target_path)
    if not parts:
        raise MountValidationError("目标路径不能指向挂载根目录本身", "invalid_argument")
    if reject_hidden and any(part.startswith(".") for part in parts):
        raise MountValidationError("禁止访问或写入隐藏目录/内部元数据文件", "path_safety")

    current = mount_root
    for part in parts:
        current = current / part
        if current.is_symlink():
            if not allow_symlinks:
                raise MountValidationError(f"禁止通过符号链接路径操作: {part}", "path_safety")
            if not current.resolve().is_relative_to(resolved_root):
                raise MountValidationError(f"符号链接逃逸出挂载根目录: {part}", "path_safety")
    resolved_target = current.resolve()
    if not resolved_target.is_relative_to(resolved_root) or resolved_target == resolved_root:
        raise MountValidationError("目标路径逃逸出 NAS 挂载根目录", "path_safety")
    return current


def is_safe_scan_entry(resolved_root: Path, entry_path: Path) -> bool:
    """Verify a discovered file or directory remains inside resolved_root without symlink escape."""
    try:
        resolved = entry_path.resolve()
        return resolved.is_relative_to(resolved_root)
    except OSError:
        return False


def read_text_bounded(
    path: Path,
    max_bytes: int,
    *,
    root_guard: Path | None = None,
    allow_symlinks: bool = False,
) -> str:
    """Read UTF-8 text safely with O_NOFOLLOW and strict byte-size limits."""
    if path.is_symlink():
        if not allow_symlinks:
            raise MountValidationError(f"拒绝读取符号链接文件: {path.name}", "path_safety")
        if root_guard is not None and not path.resolve().is_relative_to(root_guard.resolve()):
            raise MountValidationError(f"符号链接文件逃逸出受管目录: {path.name}", "path_safety")
    if root_guard is not None and not is_safe_scan_entry(root_guard.resolve(), path):
        raise MountValidationError(f"文件超出受管目录: {path.name}", "path_safety")

    flags = os.O_RDONLY | (0 if allow_symlinks else getattr(os, "O_NOFOLLOW", 0))
    fd: int | None = None
    try:
        fd = os.open(path, flags)
    except FileNotFoundError as exc:
        raise MountValidationError(f"文件不存在: {path}", "not_found") from exc
    except PermissionError as exc:
        raise MountValidationError(f"文件无读取权限: {path}", "permission_denied") from exc
    except OSError as exc:
        code = "path_safety" if exc.errno == errno.ELOOP else "service_offline"
        raise MountValidationError(f"无法打开文件 {path.name}: {exc}", code) from exc

    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode):
            raise MountValidationError(f"路径不是常规文件: {path.name}", "invalid_argument")
        if st.st_size > max_bytes:
            raise MountValidationError(f"文件大小 {st.st_size} 字节超过限制 {max_bytes}", "invalid_argument")
        with os.fdopen(fd, "rb") as handle:
            fd = None
            raw = handle.read(max_bytes + 1)
    finally:
        if fd is not None:
            os.close(fd)

    if len(raw) > max_bytes:
        raise MountValidationError(f"文件读取超过最大字节限制 {max_bytes}", "invalid_argument")
    return raw.decode("utf-8", errors="replace")


def atomic_write_text_exact(target: Path, content: str, *, mode: int = 0o644) -> Path:
    """Atomically write UTF-8 text via `.<name>.omnidesk.tmp` + `os.replace`."""
    if target.is_symlink():
        raise MountValidationError(f"拒绝写入符号链接目标: {target.name}", "path_safety")
    tmp_path = target.parent / f".{target.name}.omnidesk.tmp"
    if tmp_path.is_symlink():
        raise MountValidationError(f"拒绝写入符号链接临时文件: {tmp_path.name}", "path_safety")

    raw_bytes = content.encode("utf-8")
    flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC | getattr(os, "O_NOFOLLOW", 0)
    fd: int | None = None
    try:
        fd = os.open(tmp_path, flags, mode)
        with os.fdopen(fd, "wb") as handle:
            fd = None
            handle.write(raw_bytes)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp_path, mode)
        os.replace(tmp_path, target)
    except OSError as exc:
        if fd is not None:
            os.close(fd)
        tmp_path.unlink(missing_ok=True)
        code = "path_safety" if exc.errno == errno.ELOOP else "permission_denied"
        raise MountValidationError(f"原子写入失败: {exc}", code) from exc
    except BaseException:
        if fd is not None:
            os.close(fd)
        tmp_path.unlink(missing_ok=True)
        raise
    return tmp_path


def _load_managed_manifest(mount_root: Path) -> dict[str, dict[str, Any]]:
    manifest_path = mount_root / ".omnidesk" / "managed_subtitles.json"
    if not manifest_path.exists() and not manifest_path.is_symlink():
        return {}
    if manifest_path.is_symlink():
        raise MountValidationError("受管字幕清单不可为符号链接", "path_safety")
    raw = read_text_bounded(manifest_path, MAX_SYNC_BYTES, root_guard=mount_root)
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError:
        return {}
    if not isinstance(parsed, dict) or not isinstance(parsed.get("files"), dict):
        return {}
    return {str(k): dict(v) for k, v in parsed["files"].items() if isinstance(v, dict)}


def _save_managed_manifest(mount_root: Path, files_map: Mapping[str, Mapping[str, Any]]) -> None:
    meta_dir = mount_root / ".omnidesk"
    if meta_dir.is_symlink():
        raise MountValidationError(".omnidesk 元数据目录不可为符号链接", "path_safety")
    meta_dir.mkdir(parents=True, exist_ok=True, mode=0o755)
    manifest_path = meta_dir / "managed_subtitles.json"
    payload = {"version": 1, "files": dict(sorted(files_map.items()))}
    atomic_write_text_exact(
        manifest_path,
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        mode=0o600,
    )


def _ensure_safe_parent_dirs(mount_root: Path, target: Path) -> None:
    resolved_root = mount_root.resolve()
    rel_parent = target.parent.relative_to(mount_root)
    cur = mount_root
    for part in rel_parent.parts:
        cur = cur / part
        if cur.is_symlink():
            raise MountValidationError(f"父目录路径包含符号链接: {part}", "path_safety")
        if not cur.exists():
            cur.mkdir(mode=0o755)
        elif not cur.is_dir():
            raise MountValidationError(f"父路径不是目录: {part}", "invalid_argument")
        if not cur.resolve().is_relative_to(resolved_root):
            raise MountValidationError("父目录逃逸出挂载根目录", "path_safety")


def _is_in_managed_subdirs(rel_path: str, managed_dirs: str) -> bool:
    allowed = [seg.strip().strip("/\\") for seg in managed_dirs.split(",") if seg.strip()]
    if not allowed or "." in allowed:
        return True
    rel_norm = rel_path.replace("\\", "/").lstrip("/")
    for prefix in allowed:
        norm_prefix = prefix.replace("\\", "/").strip("/")
        if rel_norm == norm_prefix or rel_norm.startswith(f"{norm_prefix}/"):
            return True
    return False


def _has_omnidesk_marker(text: str) -> bool:
    return any(marker in text for marker in _OMNIDESK_MARKERS)


def _has_manual_marker(text: str) -> bool:
    lowered = text.lower()
    return any(marker.lower() in lowered for marker in _MANUAL_MARKERS)


def safe_write_subtitle(
    mount_root: Path,
    target_path: str,
    content: str,
    *,
    managed_dirs: str = "",
    protect_manual: bool = True,
    allow_overwrite_own: bool = True,
    overwrite_manual: bool = False,
) -> dict[str, Any]:
    """Atomically write subtitle inside managed directory, refusing manual subtitles by default."""
    if not isinstance(content, str):
        raise MountValidationError("字幕内容必须为字符串", "invalid_argument")
    encoded = content.encode("utf-8")
    if len(encoded) > MAX_SUBTITLE_BYTES:
        raise MountValidationError(f"字幕内容超过 {MAX_SUBTITLE_BYTES} 字节限制", "invalid_argument")

    target = resolve_contained_path(mount_root, target_path, allow_symlinks=False, reject_hidden=True)
    if target.suffix.lower() not in SUBTITLE_EXTENSIONS:
        raise MountValidationError(
            f"不支持的字幕扩展名 {target.suffix!r}，仅允许 {sorted(SUBTITLE_EXTENSIONS)}",
            "invalid_argument",
        )
    rel_key = target.relative_to(mount_root).as_posix()
    if not _is_in_managed_subdirs(rel_key, managed_dirs):
        raise MountValidationError(f"目标路径 {rel_key} 不在受管字幕目录范围内", "path_safety")

    with _WRITE_LOCK:
        _ensure_safe_parent_dirs(mount_root, target)
        existed = target.exists()
        if target.is_symlink():
            raise MountValidationError("禁止覆盖符号链接字幕文件", "path_safety")

        manifest = _load_managed_manifest(mount_root)
        if existed:
            existing_text = read_text_bounded(target, MAX_SUBTITLE_BYTES, root_guard=mount_root, allow_symlinks=False)
            existing_sha = hashlib.sha256(existing_text.encode("utf-8")).hexdigest()
            recorded_sha = manifest.get(rel_key, {}).get("sha256", "")
            is_managed_own = (bool(recorded_sha and recorded_sha == existing_sha) or _has_omnidesk_marker(existing_text)) and not _has_manual_marker(existing_text)

            if not is_managed_own:
                if protect_manual or not overwrite_manual:
                    raise MountValidationError(
                        f"检测到既有或人工精校字幕，默认拒绝覆盖: {rel_key}",
                        "conflict",
                        details={"reason": "manual_subtitle_protected", "path": str(target), "relative_path": rel_key},
                    )
            elif not allow_overwrite_own:
                raise MountValidationError(
                    f"已禁止覆盖既有受管字幕: {rel_key}",
                    "conflict",
                    details={"reason": "own_subtitle_locked", "path": str(target), "relative_path": rel_key},
                )

        tmp_used = atomic_write_text_exact(target, content, mode=0o644)
        new_sha = hashlib.sha256(encoded).hexdigest()
        manifest[rel_key] = {
            "sha256": new_sha,
            "bytes": len(encoded),
            "updated_at": time.time(),
        }
        _save_managed_manifest(mount_root, manifest)

    return {
        "written": True,
        "atomic": True,
        "path": str(target.resolve()),
        "relative_path": rel_key,
        "tmp_filename": tmp_used.name,
        "bytes_written": len(encoded),
        "sha256": new_sha,
        "replaced_existing": existed,
    }
