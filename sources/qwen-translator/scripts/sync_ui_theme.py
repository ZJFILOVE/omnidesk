#!/usr/bin/env python3
"""Generate identical desktop/Android design tokens; --check never writes files."""
import argparse
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parent.parent


def outputs():
    source = json.loads((ROOT / 'design/material-theme.json').read_text())
    python = ('# Generated by scripts/sync_ui_theme.py; edit design/material-theme.json.\n'
              + 'UI_FONT_FAMILIES = ' + repr(source['fontFamilies']) + '\n'
              + 'SPACING = ' + repr(source['spacing']) + '\n'
              + 'RADII = ' + repr(source['radius']) + '\n'
              + 'LAYOUT = ' + repr(source['layout']) + '\n'
              + 'THEMES = ' + pprint.pformat({key: source[key] for key in ('light', 'dark')}, sort_dicts=False) + '\n')
    kotlin = ('// Generated by scripts/sync_ui_theme.py; edit design/material-theme.json.\n'
              'package cn.qwensub.app\n\n'
              'import androidx.compose.ui.graphics.Color\n'
              'import androidx.compose.ui.unit.dp\n\n'
              'internal object MaterialTokens {\n')
    for group, prefix in [('radius', 'Radius'), ('spacing', 'Space'), ('layout', 'Layout')]:
        for key, value in source[group].items():
            name = prefix + key[0].upper() + key[1:]
            kotlin += f'    val {name} = {value}.dp\n'
    for mode in ('light', 'dark'):
        kotlin += f'\n    object {mode.title()} {{\n'
        for key, value in source[mode].items():
            name = ''.join(part.title() for part in key.split('_'))
            kotlin += f'        val {name} = Color(0xFF{value[1:]})\n'
        kotlin += '    }\n'
    kotlin += '}\n'
    xml = '<!-- Generated by scripts/sync_ui_theme.py; edit design/material-theme.json. -->\n<resources>\n'
    for mode in ('light', 'dark'):
        for key in ('base', 'accent'):
            xml += f'    <color name="material_{mode}_{key}">{source[mode][key]}</color>\n'
    xml += '</resources>\n'
    return {ROOT / 'ui_tokens.py': python,
            ROOT / 'android/app/src/main/java/cn/qwensub/app/MaterialTokens.kt': kotlin,
            ROOT / 'android/app/src/main/res/values/material_colors.xml': xml}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        parser.exit(1, 'Outdated UI tokens: ' + ', '.join(stale) + '\n')
    print('Material design tokens match.' if args.check else 'Material design tokens generated.')


if __name__ == '__main__':
    main()
